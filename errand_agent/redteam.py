"""Run the red-team playbooks (errand_agent/static/playbooks.json) offline and check each expectation.

    python -m errand_agent.redteam            # prints a table, writes docs/RED_TEAM_RESULTS.md

The same playbooks are clickable in the web UI. Here they run through the same web App, with the
deterministic rule parser and a fixed fake clock, so results are reproducible.
"""
import json
import os
import sys
import tempfile
from datetime import datetime

from .clock import FakeClock
from .web import PLAYBOOKS, App


def load() -> list:
    with open(PLAYBOOKS) as f:
        return json.load(f)


def expand(steps: list) -> list:
    out = []
    for s in steps:
        if isinstance(s, str):
            out.append(("say", s))
        elif "advance" in s:
            out.append(("advance", s["advance"]))
        elif "restart" in s:
            out.append(("restart", None))
        elif "say" in s:
            out += [("say", s["say"])] * s.get("times", 1)
        elif "repeat_text" in s:
            out.append(("say", s["repeat_text"] * s["times"]))
    return out


def run(pb: dict, root: str | None = None) -> dict:
    app = App(root or tempfile.mkdtemp(), clock_factory=lambda: FakeClock(datetime(2026, 11, 1, 8, 0)))
    app.reset({"scenario": pb.get("scenario", "default"), "parser": "rules"})
    replies = []
    for kind, arg in expand(pb["steps"]):
        if kind == "say":
            replies.append(app.message(arg)["reply"])
        elif kind == "advance":
            app.advance(arg)
        else:
            replies.append(app.restart()["reply"])
    snap = app.snapshot(0)
    new = [b for b in snap["bookings"] if not b["id"].startswith("BK-09") and b["status"] != "cancelled"]
    cancelled = [b for b in snap["bookings"] if b["status"] == "cancelled"]
    last = replies[-1] if replies else ""
    e, fails = pb["expect"], []
    if "new_bookings" in e and len(new) != e["new_bookings"]:
        fails.append(f"new_bookings={len(new)} (expected {e['new_bookings']})")
    if "cancelled" in e and len(cancelled) != e["cancelled"]:
        fails.append(f"cancelled={len(cancelled)} (expected {e['cancelled']})")
    if "stage" in e and snap["stage"] != e["stage"]:
        fails.append(f"stage={snap['stage']} (expected {e['stage']})")
    fails += [f"last reply lacks {s!r}" for s in e.get("reply_contains", []) if s not in last]
    fails += [f"last reply contains {s!r}" for s in e.get("reply_not", []) if s in last]
    fails += [f"no reply contains {s!r}" for s in e.get("any_reply_contains", []) if not any(s in r for r in replies)]
    mutations = [ev["tool"] for ev in snap["events"] if ev["type"] == "tool_call"
                 and ev["tool"] in ("book", "cancel", "reschedule")]
    return {"id": pb["id"], "passed": not fails, "fails": fails, "last": last, "stage": snap["stage"],
            "new_bookings": len(new), "mutations": mutations}


def main():
    pbs = load()
    rows, ok = [], 0
    for pb in pbs:
        r = run(pb)
        ok += r["passed"]
        print(f"{'PASS' if r['passed'] else 'FAIL'}  {pb['id']:22} {'; '.join(r['fails'])}")
        last = r["last"].splitlines()[0][:110].replace("|", "\\|") if r["last"] else ""
        rows.append(f"| {pb['group']} | **{pb['title']}**{' (scenario `' + pb['scenario'] + '`)' if pb.get('scenario') else ''} "
                    f"| {'PASS' if r['passed'] else 'FAIL'} | {r['new_bookings']} | {', '.join(r['mutations']) or '-'} "
                    f"| {last} |")
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "RED_TEAM_RESULTS.md")
    with open(path, "w") as f:
        f.write("# Red-team playbook results\n\nGenerated by `python -m errand_agent.redteam` (rule parser, fixed clock "
                f"2026-11-01 08:00). {ok}/{len(pbs)} passed. Steps and expectations are in "
                "`errand_agent/static/playbooks.json`; see `docs/RED_TEAM.md` for what each one tests.\n\n"
                "| Area | Playbook | Result | New bookings | Mutating calls | Agent's last reply |\n|---|---|---|---|---|---|\n"
                + "\n".join(rows) + "\n")
    print(f"\n{ok}/{len(pbs)} passed -> {path}")
    sys.exit(0 if ok == len(pbs) else 1)


if __name__ == "__main__":
    main()
