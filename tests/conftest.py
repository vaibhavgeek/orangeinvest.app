"""Collects scenario results and writes docs/EVAL_RESULTS.md at the end of the test run."""
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

RESULTS: dict = {}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class EvalRecord:
    def __init__(self, name):
        self.row = {"scenario": name, "expected": "", "actual": "(not reached)", "notes": "", "outcome": "?"}

    def __call__(self, expected=None, actual=None, notes=None):
        for k, v in (("expected", expected), ("actual", actual), ("notes", notes)):
            if v is not None:
                self.row[k] = v


@pytest.fixture
def ev(request):
    rec = EvalRecord(request.node.name.removeprefix("test_"))
    rec.row["expected"] = (request.node.function.__doc__ or "").strip()
    RESULTS[request.node.nodeid] = rec
    return rec


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    rec = RESULTS.get(item.nodeid)
    if rec and rep.when == "call":
        rec.row["outcome"] = "PASS" if rep.passed else "FAIL"
        if rep.failed:
            msg = str(rep.longrepr.reprcrash.message) if hasattr(rep.longrepr, "reprcrash") else str(rep.longrepr)
            rec.row["notes"] = (rec.row["notes"] + " | FAILED: " + msg.splitlines()[0])[:300]


def pytest_sessionfinish(session, exitstatus):
    rows = [r.row for nid, r in RESULTS.items() if "test_evals" in nid]
    if not rows:
        return
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    passed = sum(r["outcome"] == "PASS" for r in rows)
    out = ["# Eval results", "",
           f"Generated by `pytest` (tests/test_evals.py) — {passed}/{len(rows)} scenarios passed. "
           "Offline and deterministic: recorded OpenAI responses (tests/cassettes/), seeded mock, fake clock.", "",
           "| # | Scenario | Expected | Actual | Pass/Fail | Notes |", "|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        out.append(f"| {i} | {esc(r['scenario'])} | {esc(r['expected'])} | {esc(r['actual'])} | "
                   f"{r['outcome']} | {esc(r['notes'])} |")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "EVAL_RESULTS.md"), "w") as f:
        f.write("\n".join(out) + "\n")
